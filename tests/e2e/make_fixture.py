"""Cut a small test site out of a full local build: Orchard Road's trees and those around Dhoby Ghaut.

The integration tests (tests/e2e) run the Worker against this fixture instead of the full
~890,000-tree build. Regenerate after a schema or tile-format change:

    python -m pipeline.fetch all && python -m pipeline.build      # full build in build/out
    python tests/e2e/make_fixture.py                              # writes tests/fixtures/site/
    tippecanoe -o tests/fixtures/site/trees.pmtiles --force -l trees -Z10 -z16 -B15 -r2 \\
        --drop-densest-as-needed --extend-zooms-if-still-dropping tests/fixtures/site/trees.geojsonl

Tree data: Trees.sg © National Parks Board (an excerpt, for testing only).
"""
from __future__ import annotations

import glob
import json
import re
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "build" / "out"
DEST = ROOT / "tests" / "fixtures" / "site"
BBOX = (103.8435, 1.2975, 103.8475, 1.3005)  # around Dhoby Ghaut station; every Orchard Road tree is added too
# Invented "recent changes", so the tests have something to show (not real events).
FAKE_CHANGES = 3


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    db = sqlite3.connect(":memory:")
    for f in sorted(glob.glob(str(OUT / "d1" / "*.sql"))):
        db.executescript(Path(f).read_text())
    db.row_factory = sqlite3.Row
    trees = db.execute(
        """SELECT * FROM trees WHERE (lng BETWEEN ? AND ? AND lat BETWEEN ? AND ?)
              OR road_id=(SELECT id FROM places WHERE kind='road' AND slug='orchard-road')""",
        (BBOX[0], BBOX[2], BBOX[1], BBOX[3])).fetchall()
    ids = {t["id"] for t in trees}
    place_ids = {t[c] for t in trees for c in ("road_id", "park_id", "subzone_id", "pa_id", "pcn_id", "ed_id", "hr_id")} - {None}
    species_ids = {t["species_id"] for t in trees} - {None}
    places = [p for p in db.execute("SELECT * FROM places") if p["id"] in place_ids]
    species = [s for s in db.execute("SELECT * FROM species") if s["id"] in species_ids]
    meta = json.loads(db.execute("SELECT value FROM meta WHERE key='build'").fetchone()[0])
    meta.update(built_at="2026-01-05T00:00:00Z", tree_count=len(trees), species_count=len(species),
                source_last_edit="2026-01-04T00:00:00Z", changes={"seen": "2026-01-05", "since": "2025-12-29",
                                                                    "added": FAKE_CHANGES, "removed": FAKE_CHANGES})
    cats = {}
    for t in trees:
        cats[t["category"]] = cats.get(t["category"], 0) + 1
    meta["category_counts"] = cats

    orchard = next(p["id"] for p in places if p["kind"] == "road" and p["slug"] == "orchard-road")
    on_road = [t for t in trees if t["road_id"] == orchard]
    sp = {s["id"]: s for s in species}
    changes = []
    for i, t in enumerate(on_road[:FAKE_CHANGES]):
        s = sp.get(t["species_id"]) or {}
        changes.append((t["id"], "added", "2026-01-05", "2025-12-29", t["lng"], t["lat"], s["common"] if s else None,
                        s["scientific"] if s else None, t["girth_m"], t["road_id"], t["park_id"], t["subzone_id"], t["pa_id"], t["ed_id"]))
        changes.append((990000000 + i, "removed", "2026-01-05", "2025-12-29", t["lng"] + 0.00004, t["lat"], s["common"] if s else None,
                        s["scientific"] if s else None, t["girth_m"], t["road_id"], t["park_id"], t["subzone_id"], t["pa_id"], None))

    schema = (ROOT / "schema.sql").read_text()
    lines = ["-- Test fixture: generated by tests/e2e/make_fixture.py. Do not edit by hand.",
             "-- Tree data: Trees.sg (c) National Parks Board, an excerpt for testing only.",
             *(f"DROP TABLE IF EXISTS {t};" for t in ("trees", "species", "places", "changes", "meta")),
             re.sub(r"--[^\n]*", "", schema)]

    def insert(table, rows):
        for r in rows:
            lines.append(f"INSERT INTO {table} VALUES ({','.join(q(v) for v in tuple(r))});")
    insert("species", species)
    insert("places", places)
    insert("trees", trees)
    insert("changes", changes)
    lines.append(f"INSERT INTO meta VALUES ('build', {q(json.dumps(meta, separators=(',', ':')))});")
    DEST.mkdir(parents=True, exist_ok=True)
    (DEST / "seed.sql").write_text("\n".join(lines) + "\n")

    keep_places = {(p["kind"], p["slug"]) for p in places}
    search = [e for e in json.loads((OUT / "search.json").read_text())
              if (e["k"], e["s"]) in keep_places or (e["k"] == "species" and int(e["s"]) in species_ids)
              or (e["k"] == "mrt" and BBOX[0] <= e["ll"][1] <= BBOX[2] and BBOX[1] <= e["ll"][0] <= BBOX[3])]
    (DEST / "search.json").write_text(json.dumps(search, ensure_ascii=False, separators=(",", ":")))
    sdict = json.loads((OUT / "species.json").read_text())
    (DEST / "species.json").write_text(json.dumps({k: v for k, v in sdict.items() if int(k) in species_ids},
                                                  ensure_ascii=False, separators=(",", ":")))
    # trees.geojsonl is only the input for tippecanoe; it is not committed (see .gitignore)
    with open(OUT / "trees.geojsonl") as src, open(DEST / "trees.geojsonl", "w") as dst:
        for line in src:
            if json.loads(line)["properties"]["id"] in ids:
                dst.write(line)
    print(f"fixture: {len(trees)} trees, {len(species)} species, {len(places)} places, {len(search)} search entries",
          file=sys.stderr)


if __name__ == "__main__":
    main()
